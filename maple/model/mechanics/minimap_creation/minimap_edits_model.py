import json
import numpy as np
import os
from dataclasses import asdict, dataclass, field
from paths import ROOT
from botting.utilities import Box

_EDITS_ROOT = os.path.join(ROOT, 'configs/maps')


@dataclass(frozen=True, kw_only=True)
class MinimapEdits(Box):
    """
    A bounding Box grouping minimap nodes into a named feature with shared properties.
    """
    name: str
    offset: tuple[int, int] = field(default=(0, 0))
    walkable: bool = field(default=True)
    weight: int = field(default=1)

    avoid_right_edge: bool = field(default=False)
    avoid_left_edge: bool = field(default=False)
    edge_threshold: int = field(default=0)

    no_jump_connections_from_endpoints: bool = field(default=False)

    rotation_indexes: list[int] = field(default_factory=list)
    relative: bool = field(default=False, init=False, repr=False)

    @property
    def is_in_rotation(self) -> bool:
        return len(self.rotation_indexes) > 0

    @property
    def is_platform(self) -> bool:
        return not self.is_ladder and self.walkable

    @property
    def is_ladder(self) -> bool:
        return 0 <= self.width < 1 and self.walkable

    def is_a_blocked_endpoint(self, x: int, y: int) -> bool:
        return self.no_jump_connections_from_endpoints and x in [self.left, self.right]


@dataclass(frozen=True, kw_only=True)
class AutoGeneratedFeature(MinimapEdits):
    """
    Kept for backward compatibility with map_parser.py.
    Not used in the new JSON-based workflow.
    """
    name: str = field(compare=False)
    offset: tuple = field(default=(0, 0), init=False)
    weight: int = field(default=1, init=False)
    avoid_right_edge: bool = field(default=False, init=False)
    avoid_left_edge: bool = field(default=False, init=False)
    edge_threshold: int = field(default=0, init=False)
    no_jump_connections_from_endpoints: bool = field(default=False, init=False)
    rotation_indexes: list[int] = field(default_factory=list, init=False)


@dataclass(frozen=True)
class PortalEdge:
    """
    A directed connection between two minimap nodes (cells).
    bidirectional=True also adds the reverse connection.
    """
    source: tuple[int, int]
    target: tuple[int, int]
    bidirectional: bool = False


# Returned by _get_node_info when no feature covers a walkable node (e.g. after offset shift).
_DEFAULT_NODE_INFO = MinimapEdits(name='_auto', left=0, right=1, top=0, bottom=0)


@dataclass
class MinimapEditsManager:
    """
    Owns all feature and portal definitions for one minimap.
    The binary walkable canvas is fully derived from these definitions via build_canvas().
    """
    features: list[MinimapEdits] = field(default_factory=list)
    portals: list[PortalEdge] = field(default_factory=list)
    # Minimap-pixels-per-VR-unit; None means physics-based grid gen is unavailable.
    scale_x: float | None = None
    scale_y: float | None = None
    # Actual minimap area pixel dimensions, measured once from a live screenshot and
    # persisted so the canvas is always the right size regardless of feature coverage.
    canvas_width: int | None = None
    canvas_height: int | None = None
    # Mob names present in this map (static, never changes per map).
    mobs: list[str] = field(default_factory=list)
    # Path (relative to ROOT) of the minimap title screenshot used for map validation.
    title_img_path: str | None = None
    # Minimap (x, y) coordinate where all party members gather for synchronized
    # rebuffs. The zone around it is determined at runtime.
    party_rebuff_zone: tuple[int, int] | None = None

    @property
    def names(self) -> list[str]:
        return [f.name for f in self.features]

    def build_canvas(self) -> np.ndarray:
        """
        Construct a binary (0/1) numpy canvas purely from feature definitions.
        Uses saved canvas_width/canvas_height when available; falls back to the
        feature bounding box when the dimensions haven't been measured yet.
        """
        w = self.canvas_width or 0
        h = self.canvas_height or 0
        if w == 0 or h == 0:
            return np.zeros((1, 1), np.uint8)
        canvas = np.zeros((h, w), np.uint8)
        for feature in self.features:
            if not feature.walkable:
                continue
            canvas[feature.top:feature.bottom + 1, feature.left:feature.right + 1] = 1
        return canvas

    @classmethod
    def from_json(cls, map_name: str) -> "MinimapEditsManager | None":
        path = os.path.join(_EDITS_ROOT, f'{map_name}.json')
        if not os.path.exists(path):
            return None
        with open(path, 'r') as f:
            data = json.load(f)

        # Legacy format: top-level keys are feature names
        if 'features' not in data:
            features = [MinimapEdits(name=name, **dct) for name, dct in data.items()]
            return cls(features=features)

        meta = data.get('_meta', {})
        features = [
            MinimapEdits(name=name, **dct)
            for name, dct in data.get('features', {}).items()
        ]
        portals = [
            PortalEdge(
                source=tuple(p['source']),
                target=tuple(p['target']),
                bidirectional=p.get('bidirectional', False),
            )
            for p in data.get('portals', [])
        ]
        zone = data.get('party_rebuff_zone')
        return cls(
            features=features,
            portals=portals,
            scale_x=meta.get('scale_x'),
            scale_y=meta.get('scale_y'),
            canvas_width=meta.get('canvas_width'),
            canvas_height=meta.get('canvas_height'),
            mobs=data.get('mobs', []),
            title_img_path=data.get('title_img_path'),
            party_rebuff_zone=tuple(zone) if zone is not None else None,
        )

    def to_json(self, map_name: str) -> None:
        features_raw = asdict(self)['features']
        features_dict = {dct.pop('name'): dct for dct in features_raw}
        for dct in features_dict.values():
            dct.pop('config', None)
            dct.pop('relative', None)

        payload = {
            '_meta': {
                'scale_x': self.scale_x,
                'scale_y': self.scale_y,
                'canvas_width': self.canvas_width,
                'canvas_height': self.canvas_height,
            },
            'title_img_path': self.title_img_path,
            'mobs': self.mobs,
            'party_rebuff_zone': (
                list(self.party_rebuff_zone)
                if self.party_rebuff_zone is not None
                else None
            ),
            'features': features_dict,
            'portals': [
                {
                    'source': list(p.source),
                    'target': list(p.target),
                    'bidirectional': p.bidirectional,
                }
                for p in self.portals
            ],
        }
        os.makedirs(_EDITS_ROOT, exist_ok=True)
        with open(os.path.join(_EDITS_ROOT, f'{map_name}.json'), 'w') as f:
            json.dump(payload, f, indent=4)

    def apply_grid_edits(
        self,
        raw_minimap: np.ndarray,
        apply_weights: bool = True,
    ) -> np.ndarray:
        """
        Apply per-feature offsets and optionally weights to an existing canvas.
        Uses inclusive slicing (top:bottom+1, left:right+1) so single-row platforms
        and single-column ladders are handled correctly.
        """
        modified = raw_minimap.copy()
        for feature in self.features:
            ox, oy = feature.offset
            t, b = feature.top, feature.bottom + 1
            l, r = feature.left, feature.right + 1
            vals = modified[t:b, l:r].copy()
            modified[t:b, l:r] = 0
            if apply_weights:
                modified[t + oy:b + oy, l + ox:r + ox] = feature.weight
            else:
                modified[t + oy:b + oy, l + ox:r + ox] = vals
        return modified

    def get_feature_containing(self, mini_x: int, mini_y: int) -> MinimapEdits | None:
        vals = [
            f for f in self.features
            if f.left <= mini_x <= f.right and f.top <= mini_y <= f.bottom
        ]
        assert len(vals) <= 1, f"Multiple custom features found at {mini_x, mini_y}"
        return vals[0] if vals else None
